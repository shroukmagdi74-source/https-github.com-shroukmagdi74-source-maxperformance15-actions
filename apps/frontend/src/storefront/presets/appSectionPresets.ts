export interface FlatAppPresetSection extends AppPresetSection {
  appId: string;
  appName: string;
  category: string;
  icon?: string;
  keywords: string[];
}

export function getAllAppPresetSections(): FlatAppPresetSection[] {
  const result: FlatAppPresetSection[] = [];
  for (const app of APP_SECTION_PRESETS) {
    for (const section of app.sections) {
      result.push({
        ...section,
        appId: app.appId,
        appName: app.appName,
        category: app.category,
        icon: app.icon,
        keywords: app.keywords,
      });
    }
  }
  return result;
}

export function getAppSectionPreset(appId: string): AppSectionPresetDefinition | undefined {
  return APP_SECTION_PRESETS.find((app) => app.appId === appId);
}

export function searchAppSectionPresets(query: string): FlatAppPresetSection[] {
  const q = query.trim().toLowerCase();
  if (!q) return getAllAppPresetSections();

  const stem = q.replace(/(ة|ات|ه|ية)$/, "");

  return getAllAppPresetSections().filter((item) => {
    const searchable = [
      item.label,
      item.description,
      item.appName,
      item.category,
      item.type,
      item.badge,
      ...(item.keywords || []),
    ].join(" ").toLowerCase();

    return searchable.includes(q) || (stem.length >= 3 && searchable.includes(stem));
  });
}
