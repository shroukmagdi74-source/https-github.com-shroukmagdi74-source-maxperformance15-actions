export const resolveVelaFooterHref = (
  value: string,
  pathname: string,
  search: string,
) => {
  const trimmed = value.trim();
  if (!trimmed) {
    return '#';
  }

  if (/^(https?:|mailto:|tel:)/i.test(trimmed)) {
    return trimmed;
  }

  return buildStorefrontPath(pathname, trimmed, search);
};

