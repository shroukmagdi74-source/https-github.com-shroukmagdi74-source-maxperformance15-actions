// @vitest-environment jsdom
import React from "react";
import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import {
  render,
  screen,
  waitFor,
  fireEvent,
  cleanup,
} from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import Goals from "../hr/Goals";

const mockGet = vi.fn();

vi.mock("../../services/api", () => ({
  default: {
    get: (...args: any[]) => mockGet(...args),
  },
}));

const sampleGoals = [
  {
    id: "goal-1",
    title: "زيادة مبيعات الربع الرابع",
    description: "تحقيق نمو بنسبة 25% في المبيعات المباشرة",
    goalType: "PROJECT",
    priority: "HIGH",
    targetValue: 100000,
    currentValue: 65000,
    progress: 65,
    status: "IN_PROGRESS",
    unit: "ج.م",
    startDate: "2026-10-01T00:00:00.000Z",
    endDate: "2026-12-31T00:00:00.000Z",
    autoGenerateDaily: true,
    project: { id: "proj-1", name: "توسع التجارة الإلكترونية" },
    childGoals: [
      {
        id: "child-1",
        title: "هدف موظف المبيعات الأول",
        goalType: "EMPLOYEE",
        progress: 70,
        targetValue: 50000,
        currentValue: 35000,
      },
    ],
    tasks: [{ id: "t1", title: "مهمة متابعة العملاء" }],
  },
  {
    id: "goal-2",
    title: "تقليص وقت الاستجابة للعملاء",
    description: "الرد خلال أقل من 5 دقائق",
    goalType: "DEPARTMENT",
    priority: "URGENT",
    targetValue: 95,
    currentValue: 95,
    progress: 100,
    status: "COMPLETED",
    unit: "%",
    startDate: "2026-10-01T00:00:00.000Z",
    endDate: "2026-10-31T00:00:00.000Z",
    autoGenerateDaily: false,
    department: { id: "dep-1", name: "خدمة العملاء" },
    childGoals: [],
    tasks: [],
  },
];

const sampleStats = {
  total: 2,
  completed: 1,
  completionRate: 50.0,
  averageProgress: 82.5,
};

describe("Goals (Batch 514)", () => {
  afterEach(() => {
    cleanup();
  });

  beforeEach(() => {
    vi.clearAllMocks();
    mockGet.mockImplementation((url: string) => {
      if (url === "/projects") {
        return Promise.resolve({
          data: { projects: [{ id: "proj-1", name: "توسع التجارة الإلكترونية" }] },
        });
      }
      if (url.startsWith("/tasks/goals/stats")) {
        return Promise.resolve({ data: { stats: sampleStats } });
      }
      if (url.startsWith("/tasks/goals")) {
        return Promise.resolve({ data: { goals: sampleGoals } });
      }
      return Promise.resolve({ data: {} });
    });
  });

  it("renders goals hero, summary stats, and goals list", async () => {
    render(
      <MemoryRouter>
        <Goals />
      </MemoryRouter>,
    );

    await waitFor(() => {
      expect(screen.getByText("إدارة الأهداف")).toBeDefined();
    });

    expect(screen.getByText("زيادة مبيعات الربع الرابع")).toBeDefined();
    expect(screen.getByText("تقليص وقت الاستجابة للعملاء")).toBeDefined();
    expect(screen.getByText("82.5%")).toBeDefined();
  });

  it("filters goals by search input", async () => {
    render(
      <MemoryRouter>
        <Goals />
      </MemoryRouter>,
    );

    await waitFor(() => {
      expect(screen.getByText("زيادة مبيعات الربع الرابع")).toBeDefined();
    });

    const searchInput = screen.getByTestId("goals-search-input");
    fireEvent.change(searchInput, { target: { value: "الاستجابة" } });

    expect(screen.getByText("تقليص وقت الاستجابة للعملاء")).toBeDefined();
    expect(screen.queryByText("زيادة مبيعات الربع الرابع")).toBeNull();
  });

  it("renders child goals hierarchy snapshot", async () => {
    render(
      <MemoryRouter>
        <Goals />
      </MemoryRouter>,
    );

    await waitFor(() => {
      expect(screen.getByText("لقطة من التسلسل")).toBeDefined();
    });

    expect(screen.getByText("هدف موظف المبيعات الأول")).toBeDefined();
  });

  it("shows empty state when no goals match filters", async () => {
    render(
      <MemoryRouter>
        <Goals />
      </MemoryRouter>,
    );

    await waitFor(() => {
      expect(screen.getByText("إدارة الأهداف")).toBeDefined();
    });

    const searchInput = screen.getByTestId("goals-search-input");
    fireEvent.change(searchInput, { target: { value: "غير موجود نهائيا" } });

    expect(screen.getByText("لا توجد أهداف مطابقة")).toBeDefined();
  });
});
