export type GoalType = "COMPANY" | "DEPARTMENT" | "PROJECT" | "EMPLOYEE";
export type GoalStatus = "PENDING" | "IN_PROGRESS" | "COMPLETED" | "CANCELLED";
export type GoalPriority = "LOW" | "MEDIUM" | "HIGH" | "URGENT";

export interface EmployeeOption {
  id: string;
  firstName: string;
  lastName: string;
  employeeNumber?: string | null;
}

export interface DepartmentOption {
  id: string;
  name: string;
}

export interface ProjectOption {
  id: string;
  name: string;
}

export interface TaskOption {
  id: string;
  title: string;
  status?: string;
  measurementType?: string;
  metricTargetValue?: number | null;
  projectId?: string;
}

export interface ParentGoalOption {
  id: string;
  title: string;
  goalType: GoalType | "DAILY";
  projectId?: string | null;
}

export interface AssignmentDraft {
  id?: string;
  employeeId: string;
  title: string;
  targetValue: string;
  autoGenerateDaily: boolean;
}

export interface GoalDetails {
  id: string;
  title: string;
  description?: string | null;
  goalType: GoalType | "DAILY";
  status: GoalStatus;
  priority: GoalPriority;
  targetValue: number;
  currentValue: number;
  unit?: string | null;
  startDate: string;
  endDate: string;
  project?: ProjectOption | null;
  department?: DepartmentOption | null;
  employee?: EmployeeOption | null;
  parentGoal?: ParentGoalOption | null;
  autoGenerateDaily: boolean;
  childGoals?: Array<{
    id: string;
    title: string;
    goalType: GoalType | "DAILY";
    targetValue: number;
    employee?: EmployeeOption | null;
    autoGenerateDaily?: boolean;
  }>;
  tasks?: TaskOption[];
}

export interface GoalFormState {
  title: string;
  description: string;
  goalType: GoalType;
  status: GoalStatus;
  priority: GoalPriority;
  targetValue: string;
  currentValue: string;
  unit: string;
  startDate: string;
  endDate: string;
  projectId: string;
  departmentId: string;
  employeeId: string;
  parentGoalId: string;
  autoGenerateDaily: boolean;
  linkedTaskIds: string[];
  assignments: AssignmentDraft[];
}

