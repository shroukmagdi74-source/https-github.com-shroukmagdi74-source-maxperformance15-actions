import { describe, it, expect, vi } from "vitest";
import {
  buildGoalPayload,
  createInitialFormState,
  mapGoalDetailsToFormState,
  validateGoalForm,
} from "./helpers";

vi.mock("../../../utils/i18n-toast", () => ({
  tToast: {
    error: vi.fn(),
    success: vi.fn(),
  },
}));

describe("create-goal helpers", () => {
  it("maps goal details to form state and builds payload", () => {
    const mapped = mapGoalDetailsToFormState({
      id: "goal-1",
      title: "زيادة المبيعات",
      description: "هدف الربع الرابع",
      goalType: "EMPLOYEE",
      status: "IN_PROGRESS",
      priority: "HIGH",
      targetValue: 500,
      currentValue: 120,
      unit: "طلب",
      startDate: "2026-10-01T00:00:00.000Z",
      endDate: "2026-12-31T00:00:00.000Z",
      employee: { id: "emp-1", firstName: "سارة", lastName: "علي" },
      autoGenerateDaily: true,
      tasks: [{ id: "task-1", title: "مهمة 1", status: "PENDING" }],
    } as any);

    expect(mapped.title).toBe("زيادة المبيعات");
    expect(mapped.targetValue).toBe("500");
    expect(mapped.employeeId).toBe("emp-1");
    expect(validateGoalForm(mapped)).toBe(true);

    const payload = buildGoalPayload(mapped);
    expect(payload.title).toBe("زيادة المبيعات");
    expect(payload.targetValue).toBe(500);
    expect(payload.employeeId).toBe("emp-1");
  });

  it("rejects invalid form state", () => {
    const empty = createInitialFormState();
    expect(validateGoalForm(empty)).toBe(false);
  });
});
