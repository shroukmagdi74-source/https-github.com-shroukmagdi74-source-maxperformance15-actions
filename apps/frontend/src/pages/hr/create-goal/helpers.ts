export const toInputDate = (value?: string | null): string => {
  if (!value) {
    return "";
  }

  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return "";
  }

  return date.toISOString().split("T")[0];
};

export const toNumber = (value: string): number => {
  const parsed = Number.parseFloat(value);
  return Number.isFinite(parsed) ? parsed : 0;
};

export const ensureArray = <T>(value: unknown): T[] =>
  Array.isArray(value) ? (value as T[]) : [];

export const getHydrationErrorMessage = (error: unknown, isEdit: boolean): string => {
  const apiError = error as {
    response?: {
      status?: number;
    };
  };

  if (apiError.response?.status === 404) {
    return "الهدف المطلوب غير موجود أو تم حذفه";
  }

  if (apiError.response?.status === 403) {
    return isEdit
      ? "لا تملك صلاحية الوصول إلى هذا الهدف"
      : "لا تملك صلاحية الوصول إلى هذه البيانات";
  }

  return isEdit ? "تعذر تحميل بيانات الهدف" : "تعذر تحميل بيانات الصفحة";
};

export const getEmployeeLabel = (employee: EmployeeOption): string => {
  const fullName = `${employee.firstName || ""} ${employee.lastName || ""}`.trim();
  return employee.employeeNumber
    ? `${fullName} - ${employee.employeeNumber}`
    : fullName;
};
