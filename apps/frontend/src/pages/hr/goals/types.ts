export type GoalType =
  | "COMPANY"
  | "DEPARTMENT"
  | "PROJECT"
  | "EMPLOYEE"
  | "DAILY";

export interface GoalUser {
  id: string;
  firstName: string;
  lastName: string;
  department?: {
    id: string;
    name: string;
  } | null;
}

export interface GoalProject {
  id: string;
  name: string;
}

export interface GoalTask {
  id: string;
  title: string;
}

export interface GoalRecord {
  id: string;
  title: string;
  description?: string | null;
  goalType: GoalType;
  priority: string;
  targetValue: number;
  currentValue: number;
  progress: number;
  status: string;
  unit?: string | null;
  startDate: string;
  endDate: string;
  goalDate?: string | null;
  autoGenerateDaily: boolean;
  project?: GoalProject | null;
  employee?: GoalUser | null;
  department?: {
    id: string;
    name: string;
  } | null;
  parentGoal?: {
    id: string;
    title: string;
    goalType: GoalType;
  } | null;
  childGoals?: Array<{
    id: string;
    title: string;
    goalType: GoalType;
    progress: number;
    targetValue: number;
    currentValue: number;
    goalDate?: string | null;
    user?: GoalUser | null;
    employee?: GoalUser | null;
  }>;
  tasks?: GoalTask[];
}

export interface GoalStats {
  total: number;
  completed: number;
  completionRate: number;
  averageProgress: number;
  byType?: Array<{ goalType: GoalType; _count: number }>;
}

export interface ProjectOption {
  id: string;
  name: string;
}
