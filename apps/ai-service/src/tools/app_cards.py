# Legacy and common aliases to map to canonical app cards
_APP_SLUG_ALIASES: dict[str, str] = {
    "dental-lab": "dental-lab-app",
    "treasury-expenses": "treasury-expenses-pro",
    "treasury": "treasury-expenses-pro",
    "academy": "academy-app",
    "radiology": "radiology-app",
    "marketing-agency": "marketing-agency-pro",
    "order-shipping": "order-shipping-hub",
}


def get_app_card(slug: str) -> dict[str, Any] | None:
    """Retrieve the knowledge card for an application slug.

    Args:
        slug: The application slug (e.g. 'order-core', 'inventory-pro').

    Returns:
        A deep copy of the card dictionary if found, or None if unknown.
    """
    if not slug:
        return None
    normalized = str(slug).strip().lower()
    canonical = _APP_SLUG_ALIASES.get(normalized, normalized)
    card = APP_CARDS.get(canonical)
    if card is None:
        return None
    return copy.deepcopy(card)


def list_app_slugs() -> list[str]:
    """Return a sorted list of all registered canonical application slugs."""
    return sorted(APP_CARDS.keys())
